"""
Dataset loading, transforms, and class-weight calculation.
Uses torchvision's ImageFolder against data/processed/{train,val,test},
which were generated by prepare_data.py.
"""

import torch
from torch.utils.data import DataLoader
from torchvision import datasets, transforms

try:
    from . import config
except ImportError:
    import config  # allows running this file directly, not just as a package

# ImageNet normalization stats — required since MobileNetV2 is pretrained on ImageNet
IMAGENET_MEAN = [0.485, 0.456, 0.406]
IMAGENET_STD = [0.229, 0.224, 0.225]

train_transform = transforms.Compose([
    transforms.RandomResizedCrop(config.IMAGE_SIZE, scale=(0.8, 1.0)),
    transforms.RandomHorizontalFlip(),
    transforms.RandomRotation(15),
    # Deliberately mild color jitter: disease symptoms are often color-based
    # (yellowing, browning, rust). Aggressive color augmentation risks washing
    # out the exact signal the model needs to learn.
    transforms.ColorJitter(brightness=0.1, contrast=0.1),
    transforms.ToTensor(),
    transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
])

eval_transform = transforms.Compose([
    transforms.Resize((config.IMAGE_SIZE, config.IMAGE_SIZE)),
    transforms.ToTensor(),
    transforms.Normalize(IMAGENET_MEAN, IMAGENET_STD),
])


def get_datasets():
    train_ds = datasets.ImageFolder(config.TRAIN_DIR, transform=train_transform)
    val_ds = datasets.ImageFolder(config.VAL_DIR, transform=eval_transform)
    test_ds = datasets.ImageFolder(config.TEST_DIR, transform=eval_transform)
    return train_ds, val_ds, test_ds


def get_dataloaders():
    train_ds, val_ds, test_ds = get_datasets()

    train_loader = DataLoader(
        train_ds, batch_size=config.BATCH_SIZE, shuffle=True,
        num_workers=config.NUM_WORKERS, pin_memory=True
    )
    val_loader = DataLoader(
        val_ds, batch_size=config.BATCH_SIZE, shuffle=False,
        num_workers=config.NUM_WORKERS, pin_memory=True
    )
    test_loader = DataLoader(
        test_ds, batch_size=config.BATCH_SIZE, shuffle=False,
        num_workers=config.NUM_WORKERS, pin_memory=True
    )
    return train_loader, val_loader, test_loader


def get_class_weights(train_dataset):
    """
    Inverse-frequency class weights for CrossEntropyLoss, so mistakes on
    rare classes (e.g. Tomato Mosaic Virus, Potato healthy) are penalized
    more than mistakes on common ones (e.g. Tomato Yellow Leaf Curl Virus).
    """
    class_counts = torch.zeros(len(train_dataset.classes))
    for _, label in train_dataset.samples:
        class_counts[label] += 1

    total = class_counts.sum()
    weights = total / (len(class_counts) * class_counts)
    return weights.to(config.DEVICE)


def get_class_names(train_dataset):
    """Class names in the index order PyTorch assigned (alphabetical by folder name)."""
    return train_dataset.classes